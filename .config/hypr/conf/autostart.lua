---@module 'hl'

-- Autostart
hl.on("hyprland.start", function()
	hl.exec_cmd("/usr/bin/kdeconnect-indicator")
	hl.exec_cmd("/lib/kdeconnectd")
	hl.exec_cmd("hypridle")
	hl.exec_cmd("gnome-keyring-daemon --start --components=secrets,ssh")
	hl.exec_cmd("nm-applet --indicator")
	hl.exec_cmd("hyprctl setcursor Nordzy-hyprcursors 24")
	--    hl.exec_cmd("wpaperd -d")
	hl.exec_cmd("mpvpaper-stop")
	hl.exec_cmd("$HOME/.config/hypr-stuff/scripts/animated-wallpapers.sh daemon")
	hl.exec_cmd("[workspace 2 silent] zen-browser")
	hl.exec_cmd("[workspace 1 silent] kitty")
	hl.exec_cmd("clipse -listen")
	hl.exec_cmd("waybar&")
end)

-- Exec (run every reload)
hl.on("config.reloaded", function()
	hl.exec_cmd("swaync")
	hl.exec_cmd("fcitx5")
	hl.exec_cmd("hyprpm reload")
end)
